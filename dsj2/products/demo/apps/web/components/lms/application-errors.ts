export function applicationError(error: unknown, t: Translate) {
  const code =
    error instanceof ApiError
      ? (error.details as { code?: string } | undefined)?.code
      : undefined;
  return code && messages[code] ? t(...messages[code]) : lmsError(error, t);
}
