import { chromium, expect } from "@playwright/test";
import fs from "node:fs/promises";
import path from "node:path";
const evidence = path.resolve("docs/evidence/functional-completion-20261019/run-01");
const data = JSON.parse(await fs.readFile(".runtime/functional-completion-20261019/run-01/populated.private.json", "utf8"));
const browser = await chromium.launch({channel:"chrome",headless:true});
const context = await browser.newContext({viewport:{width:1440,height:960}});
const page = await context.newPage();
const login = async user => {
  await page.goto(data.origin+"/login");
  await page.locator('input[type="email"]').fill(user.email);
  await page.locator('input[type="password"]').fill(user.password);
  await page.getByRole("button",{name:"Войти",exact:true}).click();
  await page.waitForURL(url=>!url.pathname.includes("login"));
};
try {
  await login(data.users.superAdmin);
  await page.goto(data.origin+"/settings?tab=audit");
  await page.getByRole("heading",{name:"Журнал аудита",exact:true}).waitFor();
  await page.locator(".audit-log tbody tr").first().waitFor();
  await page.locator(".audit-log summary").first().click();
  const auditResponse=await page.request.get(data.origin+"/api/audit?page=1");
  expect(auditResponse.ok()).toBe(true);
  const audit=await auditResponse.json();
  expect(audit.total).toBeGreaterThan(0);
  expect(audit.items.every(item=>item.id&&item.action&&item.createdAt&&item.actorId)).toBe(true);
  await page.screenshot({path:path.join(evidence,"audit-final.png"),fullPage:true});
  await fs.writeFile(path.join(evidence,"AUDIT_UI_RESULT.json"),JSON.stringify({status:"PASS",total:audit.total,rows:audit.items.length,exampleActions:[...new Set(audit.items.map(item=>item.action))],actorAndTimePresent:true,detailsExpanded:true},null,2));
  await page.getByRole("button",{name:"Выйти",exact:true}).click();
  await login(data.learners[0]);
  await page.goto(data.origin+`/learn/${data.learners[0].enrollmentId}`);
  const files=page.getByRole("link",{name:"Скачать PDF",exact:true});
  await expect(files).toHaveCount(2);
  const fileHref=await files.first().getAttribute("href");
  const before=await page.request.get(new URL(fileHref,data.origin).href);
  expect(before.status()).toBe(200);
  const oldSession=await context.storageState();
  await page.getByRole("button",{name:"Выйти",exact:true}).click();
  await page.waitForURL(url=>url.pathname.includes("login"));
  const stale=await browser.newContext({storageState:oldSession});
  const rejected=await stale.request.get(new URL(fileHref,data.origin).href);
  expect(rejected.status()).toBe(401);
  await stale.close();
  await login(data.learners[0]);
  await page.goto(data.origin+`/learn/${data.learners[0].enrollmentId}`);
  await expect(files).toHaveCount(2);
  await page.screenshot({path:path.join(evidence,"learner-final.png"),fullPage:true});
  await fs.writeFile(path.join(evidence,"FINAL_UI_RESULT.json"),JSON.stringify({status:"PASS",capturedAt:new Date().toISOString(),origin:data.origin,actualLearnerLogin:true,issuedPdfCount:2,oldDocumentUrlBeforeLogout:200,revokedSessionOldDocumentUrl:401,newLoginDocumentsAvailable:true,scope:"Built runtime; actual learner session and private issued document"},null,2));
  console.log("FINAL_UI_PASS");
} finally {await browser.close();}
